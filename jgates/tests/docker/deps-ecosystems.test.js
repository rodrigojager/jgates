const MANAGERS = { uv: "uv", poetry: "poetry", pip: "pip", npm: "npm", pnpm: "pnpm", yarn: "yarn", go: "go", cargo: "cargo", dotnet: "dotnet" };

const made = [];
const tmp = (prefix) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  made.push(dir);
  return dir;
};
const write = (root, files) => {
  for (const [rel, text] of Object.entries(files)) {
    const file = path.join(root, ...rel.split("/"));
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
  }
};

function cleanup() {
  const filters = ["--filter", `label=org.jgates.test=${TEST}`, "--filter", "label=org.jgates.managed=true"];
  for (const id of docker(["ps", "-aq", ...filters]).out.split(/\s+/).filter(Boolean)) docker(["rm", "-f", id]);
  for (const name of docker(["volume", "ls", "-q", ...filters]).out.split(/\s+/).filter(Boolean)) docker(["volume", "rm", "-f", name]);
}

before(() => {
  assert.ok(dockerAvailable(), "Docker is required for npm run test:docker (the daemon did not answer)");
  assert.equal(docker(["image", "inspect", IMAGE]).code, 0, `${IMAGE} is missing; build it with npm --prefix jgates run image:build`);
  cleanup();
});

after(() => {
  try {
    for (const dir of made) fs.rmSync(dir, { recursive: true, force: true });
  } finally {
    cleanup();
  }
});

/** A synchronized project and what preparing its units needs. */
async function prepared(files, extra = {}) {
  const project = tmp("jgates-deps-eco-");
  const home = tmp("jgates-deps-home-");
  write(project, files);
  const ws = workspaceId(project);
  const image = engine.inspectImageSync(IMAGE, context);
  assert.ok(image, IMAGE);
  await sync.syncProject({ projectDir: project, workspace: ws, image: image.id, version: VERSION, home, extraLabels: TEST_LABELS, context });
  const { inventory } = discovery.discoverWorkspace(project);
  const { units } = deps.installUnits(inventory.classifications.filter((c) => c.approvable));
  const logs = path.join(home, "logs");
  const input = {
    projectDir: project,
    workspace: ws,
    home,
    version: VERSION,
    imageId: image.id,
    governed: false,
    settings: deps.loadDependencySettings(project),
    env: {},
    vault: false,
    engine: context,
    cacheVolume: CACHE,
    extraLabels: TEST_LABELS,
    logs: { dir: logs, root: home },
    ...extra,
  };
  return { project, home, ws, image: image.id, units, input };
}

/** A container like a step: no network, the source volume, the unit's volume and the cache, the recipe's step environment. */
function stepLike(w, unit, outcome, command, stdin = null) {
  const recipe = outcome.recipe;
  return engine.runInEngine(
    {
      image: w.image,
      command: ["sh", "-c", command],
      labels: engine.engineLabels({ kind: "step", version: VERSION, workspace: w.ws, extra: TEST_LABELS }),
      mounts: [
        { type: "volume", source: engine.sourceVolumeName(w.ws), target: "/workspace" },
        { type: "volume", source: outcome.volume, target: recipe.target },
        { type: "volume", source: CACHE, target: "/cache" },
      ],
      network: "none",
      workdir: unit.installRoot === "." ? "/workspace" : `/workspace/${unit.installRoot}`,
      env: { ...recipe.stepEnv, PATH: [...recipe.pathPrefix, deps.DEFAULT_IMAGE_PATH].join(":") },
      stdin,
      timeoutMs: 600_000,
    },
    context,
  );
}

const logOf = (w, outcome) => (outcome.log ? fs.readFileSync(path.join(w.home, outcome.log), "utf8") : "(no log)");

test("each manager installs into a fresh volume, a step uses the packages offline, and the second prepare reuses the volume", async () => {
  const w = await prepared(FIXTURES);
  assert.deepEqual(w.units.map((u) => u.id).sort(), Object.keys(MANAGERS).sort());
  for (const unit of w.units) {
    assert.equal(unit.info.manager, MANAGERS[unit.id], `${unit.id}: detected manager`);
    const first = await deps.prepareUnit(unit, w.input);
    assert.equal(first.status, "installed", `${unit.id}: ${first.message}\n${logOf(w, first)}`);
    assert.equal(first.volume, `${engine.dependencyVolumeName(w.ws, unit.id)}-${first.key.slice(0, 12)}`);
    const check = await stepLike(w, unit, first, VERIFY[unit.id].command);
    assert.equal(check.exitCode, 0, `${unit.id}: the step could not use the packages\n${check.stdout}\n${check.stderr}`);
    assert.ok(check.stdout.includes(VERIFY[unit.id].expect), `${unit.id}: ${check.stdout}`);
    const marker = await stepLike(w, unit, first, `cat ${first.recipe.target}/.jgates-deps.json`);
    assert.equal(JSON.parse(marker.stdout).key, first.key, `${unit.id}: the key is stored in the volume`);
    const second = await deps.prepareUnit(unit, w.input);
    assert.equal(second.status, "reused", `${unit.id}: ${second.message}`);
    assert.equal(second.volume, first.volume);
    assert.equal(second.key, first.key);
    assert.match(logOf(w, second), /no container was started|nenhum contêiner foi iniciado/);
  }
});

test("a registry token from the key store reaches the deps container only through its environment and /tmp, masked in the log, and lands in no volume or outcome", async () => {
  const vault = tmp("jgates-deps-vault-");
  const token = `npm_${crypto.randomBytes(18).toString("hex")}`;
  secrets.setSecret("NPM_TOKEN", token, { env: { SEMANTIC_GATE_HOME: vault } });
  const command = [
    'echo "npmrc: $(cat "$NPM_CONFIG_USERCONFIG" | tr "\\n" " ")"',
    'echo "token in env: $NPM_TOKEN"',
    'echo "files in /tmp: $(ls /tmp/jgates-registry)"',
    "mkdir -p node_modules/fake && echo 'module.exports = 1;' > node_modules/fake/index.js",
  ].join("; ");
  const w = await prepared(
    {
      "web/package.json": JSON.stringify({ name: "web", version: "1.0.0", private: true }, null, 2) + "\n",
      "web/bun.lock": "{}\n",
      ".jgates/dependencies.yml": `schemaVersion: 1\nregistries:\n  node:\n    url: https://registry.example.invalid/npm/\n    tokenSecret: NPM_TOKEN\ninstall:\n  command: ${JSON.stringify(command)}\n`,
    },
    { env: { SEMANTIC_GATE_HOME: vault }, vault: true },
  );
  assert.equal(w.units.length, 1);
  const unit = w.units[0];
  assert.equal(unit.info.manager, "bun");
  const outcome = await deps.prepareUnit(unit, w.input);
  const log = logOf(w, outcome);
  assert.equal(outcome.status, "installed", `${outcome.message}\n${log}`);
  assert.equal(outcome.registry.source, "vault");
  // The token was in the container's environment (the command printed it) and the log has only the mask.
  assert.match(log, /token in env: \*{8}/);
  assert.ok(!log.includes(token), "the log never holds the token");
  // The registry configuration was written in /tmp and references the variable, not the value.
  assert.match(log, /npmrc: registry=https:\/\/registry\.example\.invalid\/npm\/ \/\/registry\.example\.invalid\/npm\/:_authToken=\$\{JGATES_REGISTRY_TOKEN\}/);
  assert.match(log, /files in \/tmp: npmrc/);
  assert.ok(!JSON.stringify(deps.publicOutcome(outcome)).includes(token), "the outcome never holds the token");
  // No file of the dependency volume, the source volume or the cache holds it.
  for (const volume of [outcome.volume, engine.sourceVolumeName(w.ws), CACHE]) {
    const scan = await engine.runInEngine(
      {
        image: w.image,
        command: ["sh", "-c", 'IFS= read -r T; if grep -rqF -- "$T" /scan; then echo FOUND; else echo CLEAN; fi'],
        labels: engine.engineLabels({ kind: "helper", version: VERSION, workspace: w.ws, extra: TEST_LABELS }),
        mounts: [{ type: "volume", source: volume, target: "/scan", readonly: true }],
        stdin: `${token}\n`,
        timeoutMs: 120_000,
      },
      context,
    );
    assert.equal(scan.stdout.trim(), "CLEAN", `${volume}: ${scan.stdout}${scan.stderr}`);
  }
  // The project itself is untouched (nothing was written into it).
  assert.deepEqual(fs.readdirSync(path.join(w.project, "web")).sort(), ["bun.lock", "package.json"]);
});
