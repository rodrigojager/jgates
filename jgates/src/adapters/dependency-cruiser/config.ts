// The dependency-cruiser configuration JGates generates in the run folder (owner: generated). It carries only how the
// graph is read: what is not followed and what is left out. The rules of .jgates/architecture.yml are not translated
// into dependency-cruiser's `forbidden` list; the architecture evaluator applies them to the normalized graph, so the
// same contract judges every ecosystem and an alias the tool cannot resolve stays visible as coverage.

/** Folders that never belong to the analysed graph. */
export const EXCLUDED_PATHS = ["(^|/)node_modules/", "(^|/)dist/", "(^|/)build/", "(^|/)coverage/", "(^|/)\\.venv/", "(^|/)\\.git/", "(^|/)\\.jgates/"];

export const GENERATED_CONFIG_NAME = "depcruise.config.cjs";

export function generatedConfig(options: { architectureFile: string; ruleIds: string[] }): string {
  const header = [
    "// Generated by JGates for this run. Do not edit: the source of the rules is " + options.architectureFile + ".",
    "// Rules handled by the JGates evaluator on the normalized graph: " + (options.ruleIds.length > 0 ? options.ruleIds.join(", ") : "(none)"),
  ];
  const body = {
    forbidden: [],
    options: {
      doNotFollow: { path: "(^|/)node_modules/" },
      exclude: { path: EXCLUDED_PATHS.join("|") },
      tsPreCompilationDeps: true,
      combinedDependencies: false,
      enhancedResolveOptions: { exportsFields: ["exports"], conditionNames: ["import", "require", "node", "default", "types"] },
    },
  };
  return `${header.join("\n")}\nmodule.exports = ${JSON.stringify(body, null, 2)};\n`;
}
